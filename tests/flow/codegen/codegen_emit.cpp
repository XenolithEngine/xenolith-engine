// The generator, over the corpus.
//
// Three claims, and each is a comparison rather than an inspection. The generator is deterministic:
// the same graph written twice is the same bytes. The committed corpus is fresh: regenerating each
// case in memory gives the number the committed unit carries, so a unit that fell behind the graphs
// fails here with the words to fix it. And a unit describes the graph it was written from: loaded
// against the registry, it answers RuntimeGraph::describe() with the same value - through the same
// describer, so what is being compared is two tables.
//
// `flowtest --emit=tests/flow/codegen/gen codegen-emit` writes the corpus, the seeds and their
// manifests (the directory is relative to where it runs); every other run only checks.

#include "codegen_fixture.h"
#include "synth_cases.h"
#include "gen/synth_manifest.gen.h"

#include "../tests.h"
#include "../check/flow_check.h"

#include "SPFilesystem.h"

