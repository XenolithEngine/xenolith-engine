// The stems the payload is built from: enough of them that the list is a list, and all shaped like
// the identifiers this widget exists to find.
static const StringView s_prefixes[] = {
	StringView("Vertex"), StringView("Fragment"), StringView("Compute"), StringView("Material"),
	StringView("Texture"), StringView("Buffer"), StringView("Render"), StringView("Scene"),
	StringView("Node"), StringView("Sprite"), StringView("Label"), StringView("Layout"),
	StringView("Shadow"), StringView("Light"), StringView("Camera"), StringView("Particle"),
};

static const StringView s_suffixes[] = {
	StringView("Pass"), StringView("Attachment"), StringView("Descriptor"), StringView("Cache"),
	StringView("Builder"), StringView("Component"), StringView("System"), StringView("Queue"),
};

// The two strings that break a naive implementation, and are therefore never generated by accident.
static const StringView s_specials[] = {
	// Two astral characters: every index after them differs by one between code points and UTF-16.
	StringView("🔴🔵BlendState"),
	// The Turkish dotted capital I: its lowercase form is LONGER in bytes than the original, so a
	// Prefix-mode range taken from the lowered string does not transfer unchanged.
	StringView("İnputListener"),
	// A plain neighbour of the emoji row, so "the emoji row sorted above/below this" is checkable.
	StringView("BlendStateCache"),
};

Value ackValue(bool ok) {
	Value ret;
	ret.setBool(ok, "ok");
	return ret;
}

