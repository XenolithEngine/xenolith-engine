void emitHeader(const Schema &schema, String &out) {
	out.clear();
	appendBanner(schema, out);
	out.append(mem_std::toString("#ifndef ", schema.guard, "\n#define ", schema.guard, "\n\n"));
	auto materials = schema.hasData();
	auto vertexes = schema.hasVertexes();
	out.append("#include \"sprt_glsl.h\"\n\n");
	if (materials || vertexes) {
		out.append("#ifndef SP_GLSL\n");
		if (materials) {
			out.append("#include \"XL3dMaterial.h\"\n");
		}
		if (vertexes) {
			out.append("#include \"XL3dVertex.h\"\n");
		}
		out.append("#endif\n\n");
	}
	out.append(mem_std::toString("#ifndef SP_GLSL\nnamespace STAPPLER_VERSIONIZED ", schema.ns,
			" {\n\nusing namespace sprt::glsl;\n"));
	if (materials || vertexes) {
		out.append("namespace xl3d = STAPPLER_VERSIONIZED_NAMESPACE::xenolith::basic3d;\n");
	}
	out.append("\n#endif\n");

	for (auto &item : schema.items) {
		auto imported = item.record ? schema.records[item.index].imported
									: schema.constants[item.index].imported;
		if (imported) {
			continue;
		}
		out.push_back('\n');
		if (item.record) {
			appendRecord(schema.records[item.index], out);
		} else {
			appendConstant(schema.constants[item.index], out);
		}
	}

	out.append("\n#ifndef SP_GLSL\n");
	for (auto &r : schema.records) {
		if (!r.imported && r.isData()) {
			appendBuilder(r, out);
			out.push_back('\n');
		} else if (!r.imported && r.kind == RecordKind::Vertex) {
			appendVertexBuilder(r, out);
			out.push_back('\n');
		}
	}
	appendAsserts(schema, out);
	out.append(mem_std::toString("\n} // namespace ", schema.ns, "\n#endif\n"));
	out.append(mem_std::toString("\n#endif /* ", schema.guard, " */\n"));
}

// A mesh's vertex unpacked, and vertex(i), which reads and unpacks the i-th from the draw's mesh
void appendVertexReader(const Record &v, const Interface &iface, String &out) {
	bool oct = false;
	out.append(mem_std::toString("\n// ", v.name, " unpacked\nstruct ", v.name, "Vertex {\n"));
	for (auto &f : v.fields) {
		if (!f.padding) {
			out.append(mem_std::toString("\t", f.type->packed() ? f.type->unpacked : f.type->name,
					" ", f.name, ";\n"));
			oct = oct || f.type->name == "oct16";
		}
	}
	out.append("};\n");
	if (oct) {
		out.append("\n// a unit vector from its octahedral form (basic3d::packOct16)\n"
				   "vec3 xl3dUnpackOct16(uint v) {\n"
				   "\tvec2 e = unpackSnorm2x16(v);\n"
				   "\tvec3 n = vec3(e, 1.0 - abs(e.x) - abs(e.y));\n"
				   "\tfloat t = max(-n.z, 0.0);\n"
				   "\tn.xy += vec2(n.x >= 0.0 ? -t : t, n.y >= 0.0 ? -t : t);\n"
				   "\treturn normalize(n);\n"
				   "}\n");
	}
	out.append(mem_std::toString("\n", v.name, "Vertex vertex(uint i) {\n\t", v.name,
			" p = ", v.name, "Buffer(", iface.pushName, ".", iface.vertexPointer,
			").vertexes[i];\n\t", v.name, "Vertex v;\n"));
	for (auto &f : v.fields) {
		if (f.padding) {
			continue;
		}
		if (f.type->packed()) {
			out.append(mem_std::toString("\tv.", f.name, " = ", f.type->unpack, "(p.", f.name,
					");\n"));
		} else {
			out.append(mem_std::toString("\tv.", f.name, " = p.", f.name, ";\n"));
		}
	}
	out.append("\treturn v;\n}\n");
}

// The extensions and the includes; the push constants, the buffers they point to and a function to
// read each; in a fragment shader the samplers, and the depth for a translucent one; the varyings,
// out of a vertex shader and into a fragment one, and a fragment shader's colour.
void emitPreamble(const Schema &schema, const Shader &shader, String &out) {
	auto &iface = *shader.interface;
	auto frag = shader.stage == Stage::Fragment;

	out.clear();
	appendBanner(schema, out);
	out.append(mem_std::toString("// The interface of ", shader.name, ": ", iface.name));
	if (shader.varyings) {
		out.append(mem_std::toString(", the varyings ", shader.varyings->name));
	}
	out.append(shader.translucent ? ", translucent\n" : "\n");
	if (!iface.doc.empty()) {
		out.append("//\n");
		appendDocLines(out, iface.doc, "");
	}

	out.append("\n#extension GL_ARB_separate_shader_objects : enable\n");
	if (!iface.buffers.empty()) {
		out.append("#extension GL_EXT_buffer_reference : require\n"
				   "#extension GL_EXT_buffer_reference_uvec2 : require\n");
	}
	if (frag && !iface.samplers.empty()) {
		out.append("#extension GL_EXT_nonuniform_qualifier : enable\n");
	}
	out.append("\n#ifndef SP_GLSL\n#define SP_GLSL\n#endif\n\n#include \"sprt_glsl.h\"\n");
	Vector<StringView> seen;
	if (iface.push) {
		appendInclude(seen, iface.push->header, out);
	}
	for (auto &b : iface.buffers) { appendInclude(seen, b.record->header, out); }
	for (auto data : {shader.material, shader.block, shader.vertex}) {
		if (data) {
			appendInclude(seen, data->header, out);
		}
	}
	if (schema.hasHeader()) {
		appendInclude(seen, filepath::lastComponent(StringView(schema.output)), out);
	}

	if (iface.push) {
		out.append(mem_std::toString("\nlayout (std430, push_constant) uniform PushConstants {\n\t",
				iface.push->name, " ", iface.pushName, ";\n};\n"));
	}
	for (auto &b : iface.buffers) {
		out.append(mem_std::toString(
				"\nlayout (std430, buffer_reference, buffer_reference_align = ", b.record->align,
				") readonly buffer ", b.record->name, "Buffer {\n\t", b.record->name, " ", b.name,
				b.single ? "" : "[]", ";\n};\n"));
	}
	// a draw's material and its view's block, each read by a function of its kind's name
	struct Data {
		const Record *record;
		StringView name;
		const String &pointer;
	} data[] = {
		{shader.material, "material", iface.materialPointer},
		{shader.block, "block", iface.blockPointer},
	};
	for (auto &it : data) {
		if (it.record) {
			out.append(mem_std::toString(
					"\nlayout (std430, buffer_reference, buffer_reference_align = ",
					it.record->align, ") readonly buffer ", it.record->name, "Buffer {\n\t",
					it.record->name, " ", it.name, ";\n};\n"));
		}
	}
	if (auto v = shader.vertex) {
		out.append(mem_std::toString(
				"\nlayout (std430, buffer_reference, buffer_reference_align = ", v->align,
				") readonly buffer ", v->name, "Buffer {\n\t", v->name, " vertexes[];\n};\n"));
	}

	if (frag) {
		if (!iface.samplers.empty()) {
			out.push_back('\n');
		}
		for (auto &it : iface.samplers) {
			out.append(mem_std::toString("layout (set = 0, binding = ", it.binding, ") uniform ",
					it.type, " ", it.name, "[", it.count, "];\n"));
		}
		if (shader.translucent && iface.depth.present) {
			out.append(mem_std::toString("\nlayout (input_attachment_index = ", iface.depth.index,
					", set = 0, binding = ", iface.depth.binding, ") uniform subpassInput ",
					iface.depth.name, ";\n"));
		}
	}

	if (auto v = shader.varyings) {
		out.push_back('\n');
		appendDocLines(out, v->doc, "");
		out.append(mem_std::toString("layout (location = 0) ", frag ? "in " : "out ", v->name,
				" {\n"));
		for (auto &f : v->fields) {
			auto oneLine = isOneLine(f.doc);
			if (!oneLine) {
				appendDocLines(out, f.doc, "\t");
			}
			out.append(
					mem_std::toString("\t", f.flat ? "flat " : "", f.type->name, " ", f.name, ";"));
			if (oneLine && !f.doc.empty()) {
				out.append(mem_std::toString(" // ", f.doc));
			}
			out.push_back('\n');
		}
		out.append("} vary;\n");
	}
	if (frag) {
		out.append("\nlayout (location = 0) out vec4 outColor;\n");
	}

	if (!iface.buffers.empty() || shader.material || shader.block || shader.vertex) {
		out.push_back('\n');
	}
	for (auto &b : iface.buffers) {
		auto pointer =
				mem_std::toString(b.record->name, "Buffer(", iface.pushName, ".", b.pointer, ")");
		if (b.single) {
			out.append(mem_std::toString(b.record->name, " ", b.name, "() { return ", pointer, ".",
					b.name, "; }\n"));
		} else {
			out.append(mem_std::toString(b.record->name, " ", b.name, "(uint i) { return ", pointer,
					".", b.name, "[i]; }\n"));
		}
	}
	for (auto &it : data) {
		if (it.record) {
			out.append(mem_std::toString(it.record->name, " ", it.name, "() { return ",
					it.record->name, "Buffer(", iface.pushName, ".", it.pointer, ").", it.name,
					"; }\n"));
		}
	}
	if (auto v = shader.vertex) {
		appendVertexReader(*v, iface, out);
	}
}

