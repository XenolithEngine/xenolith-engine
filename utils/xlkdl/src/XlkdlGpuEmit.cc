// A doc of one line goes after what it describes; of several, before it, a comment line each.
void appendDocLines(String &out, StringView doc, StringView indent) {
	while (!doc.empty()) {
		auto line = doc.readUntil<StringView::Chars<'\n'>>();
		out.append(mem_std::toString(indent, "//", line.empty() ? "" : " ", line, "\n"));
		if (doc.is('\n')) {
			++doc;
		}
	}
}

bool isOneLine(StringView doc) { return doc.find('\n') == maxOf<size_t>(); }

void appendConstant(const Constant &c, String &out) {
	appendDocLines(out, c.doc, "");
	out.append(mem_std::toString("#define ", c.macro, " ", c.value, "\n"));
}

void appendRecord(const Record &r, String &out) {
	appendDocLines(out, r.doc, "");
	out.append(mem_std::toString("struct ", r.name, " {\n"));
	for (auto &f : r.fields) {
		auto oneLine = isOneLine(f.doc);
		if (!oneLine) {
			appendDocLines(out, f.doc, "\t");
		}
		out.append(mem_std::toString("\t", f.type->spelled(), " ", f.name));
		if (f.count) {
			out.append(mem_std::toString("[", f.count, "]"));
		}
		out.push_back(';');
		if (oneLine && !f.doc.empty()) {
			out.append(mem_std::toString(" // ", f.doc));
		}
		out.push_back('\n');
	}
	out.append("};\n");
}

// The layout the shaders read, checked against the one C++ makes
void appendAsserts(const Schema &schema, String &out) {
	out.append("// the records as std430 lays them out, which C++ has to agree with\n");
	for (auto &r : schema.records) {
		if (r.imported) {
			continue;
		}
		out.append(mem_std::toString("static_assert(sizeof(", r.name, ") == ", r.size, ");\n"));
		for (auto &f : r.fields) {
			out.append(mem_std::toString("static_assert(__builtin_offsetof(", r.name, ", ", f.name,
					") == ", f.offset, ");\n"));
		}
	}
}

// The license of the schema, if it has one, and where the file comes from.
void appendBanner(const Schema &schema, String &out) {
	if (!schema.copyright.empty() || !schema.license.empty()) {
		out.append("/**\n");
		if (!schema.copyright.empty()) {
			out.append(mem_std::toString(" Copyright (c) ", schema.copyright, "\n"));
		}
		if (!schema.license.empty()) {
			out.append(mem_std::toString(" SPDX-License-Identifier: ", schema.license, "\n"));
		}
		out.append("**/\n\n");
	}
	out.append(mem_std::toString("// Generated by xlkdl gpu from ",
			filepath::lastComponent(schema.file), ". Do not edit: regenerate it.\n\n"));
}

// A material's or a block's builder for C++: its fields, textures as textures; its schema; and
// make(), which lays them out as the record and hands the pass the textures, whose slots it writes
// each frame.
void appendBuilder(const Record &r, String &out) {
	auto block = r.kind == RecordKind::Block;
	appendDocLines(out,
			mem_std::toString(r.name, " with its textures, for ",
					block ? "View3d::setBlock" : "Material3d::data",
					" of a pipeline that reads it"),
			"");
	out.append(mem_std::toString("struct ", r.name, block ? "Block" : "Material", " {\n"));
	uint32_t textures = 0;
	for (auto &f : r.fields) {
		if (f.padding) {
			continue;
		}
		if (f.type->texture) {
			out.append(mem_std::toString("\txl3d::MaterialTexture3d ", f.name, ";\n"));
			++textures;
			continue;
		}
		auto zero = f.type->name == "float"							? " = 0.0f"
				: (f.type->name == "uint" || f.type->name == "int") ? " = 0"
																	: "";
		out.append(mem_std::toString("\t", f.type->name, " ", f.name));
		if (f.count) {
			out.append(mem_std::toString("[", f.count, "]"));
		} else {
			out.append(zero);
		}
		out.append(";\n");
	}
	out.push_back('\n');
	if (textures) {
		out.append("\tstatic constexpr xl3d::MaterialTextureField3d Textures[] = {\n");
		for (auto &f : r.fields) {
			if (f.type->texture) {
				out.append(mem_std::toString("\t\t{", f.offset, ", xl3d::MaterialTextureKind3d::",
						f.type->texture == 1 ? "Texture2d" : "TextureArray", "},\n"));
			}
		}
		out.append("\t};\n");
	}
	out.append(mem_std::toString("\tstatic constexpr xl3d::MaterialSchema3d Schema{\"", r.name,
			"\", ", r.size, ", ", r.align, ", ", textures ? "Textures" : "nullptr", ", ", textures,
			"};\n\n"));
	out.append(mem_std::toString("\tsprt::Rc<xl3d::MaterialData3d> make() const {\n\t\t", r.name,
			" d;\n"));
	String list;
	for (auto &f : r.fields) {
		if (f.padding) {
			out.append(mem_std::toString("\t\td.", f.name, " = 0;\n"));
		} else if (f.type->texture) {
			out.append(mem_std::toString("\t\td.", f.name,
					" = 0xFFFFFFFFu; // the pass writes the frame's slot\n"));
			list.append(mem_std::toString(list.empty() ? "" : ", ", f.name));
		} else if (f.count) {
			out.append(mem_std::toString("\t\tfor (uint32_t i = 0; i < ", f.count, "; ++i) { d.",
					f.name, "[i] = ", f.name, "[i]; }\n"));
		} else {
			out.append(mem_std::toString("\t\td.", f.name, " = ", f.name, ";\n"));
		}
	}
	out.append(mem_std::toString("\t\treturn xl3d::MaterialData3d::make(&Schema, d, {", list,
			"});\n\t}\n};\n"));
}

// A vertex's builder for C++: its fields unpacked, its format, and pack(), which makes the record
// Mesh3d::make lays out.
void appendVertexBuilder(const Record &r, String &out) {
	appendDocLines(out, mem_std::toString(r.name, " unpacked, for Mesh3d::make"), "");
	out.append(mem_std::toString("struct ", r.name, "Vertex {\n"));
	for (auto &f : r.fields) {
		if (f.padding) {
			continue;
		}
		auto type = f.type->packed() ? f.type->unpacked : f.type->name;
		auto zero = type == "float" ? " = 0.0f" : (type == "uint" || type == "int") ? " = 0" : "";
		out.append(mem_std::toString("\t", type, " ", f.name, zero, ";\n"));
	}
	out.append(mem_std::toString("\n\tstatic constexpr xl3d::VertexFormat3d Format{\"", r.name,
			"\", ", r.size, ", ", r.align, ", ", r.findField(r.position)->offset, "};\n\n"));
	out.append(mem_std::toString("\t", r.name, " pack() const {\n\t\t", r.name, " d;\n"));
	for (auto &f : r.fields) {
		if (f.padding) {
			out.append(mem_std::toString("\t\td.", f.name, " = 0;\n"));
		} else if (f.type->packed()) {
			out.append(mem_std::toString("\t\td.", f.name, " = xl3d::", f.type->pack, "(", f.name,
					");\n"));
		} else {
			out.append(mem_std::toString("\t\td.", f.name, " = ", f.name, ";\n"));
		}
	}
	out.append("\t\treturn d;\n\t}\n};\n");
}

void appendInclude(Vector<StringView> &seen, StringView header, String &out) {
	if (header.empty()) {
		return;
	}
	for (auto &it : seen) {
		if (it == header) {
			return;
		}
	}
	seen.emplace_back(header);
	out.append(mem_std::toString("#include \"", header, "\"\n"));
}

