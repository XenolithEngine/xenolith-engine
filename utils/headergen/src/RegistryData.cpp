void RegistryData::writeHooks(mem_pool::StringStream &out, StringView guard,
		SpanView<StringView> commands, StringView ctx) {
	if (commands.empty()) {
		return;
	}

	out << "#if " << guard << "\n\n";

	for (auto &it : commands) {
		bool aliased = false;

		auto cmd = getCommand(it);
		while (cmd->canonical) {
			cmd = cmd->canonical;
			aliased = true;
		}

		StringView tag;

		out << "static ";
		for (auto &v : cmd->proto.strings) {
			if (v == cmd->name) {
				out << "xl_hook_" << ctx << "_" << it;
				if (v != it) {
					if (v.size() > it.size()) {
						tag = StringView(v.data() + it.size(), v.size() - it.size());
					} else {
						tag = StringView(it.data() + v.size(), it.size() - v.size());
					}
				}
			} else {
				out << v;
			}
		}

		out << "(";
		bool first = true;
		for (auto &param : cmd->params) {
			if (first) {
				first = false;
			} else {
				out << ", ";
			}
			for (auto &v : param.strings) {
				if (v == param.type && aliased) {
					auto vIt = types.find(v);
					if (vIt != types.end()) {
						if (vIt->second.aliases.empty()) {
							out << v;
						} else if (vIt->second.aliases.size() == 1) {
							out << vIt->second.aliases.front();
						} else {
							bool found = false;
							for (auto &n : vIt->second.aliases) {
								if (n.ends_with(tag)) {
									out << n;
									found = true;
									break;
								}
							}
							if (!found) {
								out << v;
							}
						}
					} else {
						out << v;
					}
				} else {
					out << v;
				}
			}
		}
		out << ") {\n"
		"\tauto __fn = " << ctx << ".table->" << it << ";\n"
		"\tif (" << ctx << ".replace && " << ctx << ".replace->" << it << ") {\n"
		"\t\t__fn = " << ctx << ".replace->" << it << ";\n"
		"\t}\n"
		"\tif (" << ctx << ".preCall) { " << ctx << ".preCall(" << ctx << ".ctx, \"" << it << "\", (PFN_vkVoidFunction)__fn); }\n";
		if (cmd->proto.type != "void") {
			out << "\tauto ret = __fn(";
			first = true;
			for (auto &param : cmd->params) {
				if (first) {
					first = false;
				} else {
					out << ", ";
				}
				out << param.name;
			}
			out << ");\n";
			out << "\tif (" << ctx << ".postCall) { " << ctx << ".postCall(" << ctx << ".ctx, \""
				<< it << "\", (PFN_vkVoidFunction)__fn); }\n";
			out << "\treturn ret;\n";
		} else {
			out << "\t__fn(";
			first = true;
			for (auto &param : cmd->params) {
				if (first) {
					first = false;
				} else {
					out << ", ";
				}
				out << param.name;
			}
			out << ");\n";
			out << "\tif (" << ctx << ".postCall) { " << ctx << ".postCall(" << ctx << ".ctx, \""
				<< it << "\", (PFN_vkVoidFunction)__fn); }\n";
		}

		out << "}\n\n";
	}

	out << "#endif /* " << guard << " */\n\n";
}

void RegistryData::writeHooksAddr(mem_pool::StringStream &out, StringView guard,
		SpanView<StringView> commands, StringView ctx) {
	if (commands.empty()) {
		return;
	}

	out << "#if " << guard << "\n";

	for (auto &it : commands) {
		out << "\tif (strcmp(pName, \"" << it << "\") == 0) { return (PFN_vkVoidFunction)&xl_hook_"
			<< ctx << "_" << it << "; }\n";
	}

	out << "#endif /* " << guard << " */\n";
}

void RegistryData::write() {
	Set<StringView> writtenLoader;
	Set<StringView> writtenInstance;
	Set<StringView> writtenDevice;

	mem_pool::StringStream loaderHeader;
	mem_pool::StringStream instanceHeader;
	mem_pool::StringStream deviceHeader;

	mem_pool::StringStream loaderConstructor;
	mem_pool::StringStream instanceConstructor;
	mem_pool::StringStream deviceConstructor;

	mem_pool::StringStream instanceHooks;
	mem_pool::StringStream deviceHooks;

	mem_pool::StringStream instanceHooksAddr;
	mem_pool::StringStream deviceHooksAddr;

	for (auto &feature : features) {
		auto guard = toString("defined(", feature.name, ")");

		Vector<StringView> deviceCmds;
		Vector<StringView> instanceCmds;
		Vector<StringView> loaderCmds;

		if (feature.name == "VK_VERSION_1_0") {
			// reorder vkGetInstanceProcAddr for constructor
			loaderCmds.emplace_back("vkGetInstanceProcAddr");
			instanceCmds.emplace_back("vkGetInstanceProcAddr");
			deviceCmds.emplace_back("vkGetDeviceProcAddr");
		}

		for (auto &req : feature._requires) {
			for (auto &c : req.commands) {
				auto cmd = getCommand(c);

				auto list = &writtenLoader;
				auto cmds = &loaderCmds;
				if (cmd->rootType == "VkDevice") {
					cmds = &deviceCmds;
					list = &writtenDevice;
				} else if (cmd->rootType == "VkInstance") {
					cmds = &instanceCmds;
					list = &writtenInstance;
				}

				if (c != "vkGetInstanceProcAddr") {
					auto iit = list->find(c);
					if (iit == list->end()) {
						cmds->emplace_back(c);
						list->emplace(c);
					}
				}
				cmd->guard = guard;
			}
		}

		writeCommandFields(deviceHeader, guard, deviceCmds);
		writeCommandFields(instanceHeader, guard, instanceCmds);
		writeCommandFields(loaderHeader, guard, loaderCmds);
		writeLoaderConstructor(loaderConstructor, guard, loaderCmds);
		writeInstanceConstructor(instanceConstructor, guard, instanceCmds);
		writeDeviceConstructor(deviceConstructor, guard, deviceCmds);

		writeHooks(instanceHooks, guard, instanceCmds, "tl_instanceHookTable");
		writeHooks(deviceHooks, guard, deviceCmds, "tl_deviceHookTable");
		writeHooksAddr(instanceHooksAddr, guard, instanceCmds, "tl_instanceHookTable");
		writeHooksAddr(deviceHooksAddr, guard, deviceCmds, "tl_deviceHookTable");
	}

	for (auto &ext : extensions) {
		if (ext.supported == "disabled") {
			continue;
		}

		Map<SpanView<Pair<StringView, StringView>>, Vector<StringView>> deviceCmds;
		Map<SpanView<Pair<StringView, StringView>>, Vector<StringView>> instanceCmds;

		for (auto &req : ext.commands) {
			for (auto &c : req.commands) {
				auto cmd = getCommand(c);

				auto list = &writtenInstance;
				auto cmds = &instanceCmds;
				if (cmd->rootType == "VkDevice" && ext.type != "instance") {
					cmds = &deviceCmds;
					list = &writtenDevice;
				}

				auto v = cmds->find(makeSpanView(cmd->_requires));
				if (v == cmds->end()) {
					v = cmds->emplace(makeSpanView(cmd->_requires), Vector<StringView>()).first;
				}

				auto iit = list->find(c);
				if (iit == list->end()) {
					v->second.emplace_back(c);
					list->emplace(c);
				}
				cmd->guard = makeGuard(ext.name, cmd->_requires);
			}
		}

		for (auto &cmd : deviceCmds) {
			auto guard = makeGuard(ext.name, cmd.first);
			writeCommandFields(deviceHeader, guard, cmd.second);
			writeDeviceConstructor(deviceConstructor, guard, cmd.second);
			writeHooks(deviceHooks, guard, cmd.second, "tl_deviceHookTable");
			writeHooksAddr(deviceHooksAddr, guard, cmd.second, "tl_deviceHookTable");
		}
		for (auto &cmd : instanceCmds) {
			auto guard = makeGuard(ext.name, cmd.first);
			writeCommandFields(instanceHeader, guard, cmd.second);
			writeInstanceConstructor(instanceConstructor, guard, cmd.second);
			writeHooks(instanceHooks, guard, cmd.second, "tl_instanceHookTable");
			writeHooksAddr(instanceHooksAddr, guard, cmd.second, "tl_instanceHookTable");
		}
	}

	sprt::cout << "--- LOADER ---\n" << loaderHeader.weak() << "\n";
	sprt::cout << "--- INSTANCE ---\n" << instanceHeader.weak() << "\n";
	sprt::cout << "--- DEVICE ---\n" << deviceHeader.weak() << "\n";

	auto headerPath = filesystem::currentDir<Interface>("gen/XLVkTable.h");
	filesystem::mkdir(FileInfo(filepath::root(headerPath)));
	filesystem::remove(FileInfo(headerPath));

	std::ofstream headerFile(headerPath.data());
	headerFile << FILE_HEADER_STRING
		<< "\n#ifndef XENOLITH_BACKEND_VK_XLVKTABLE_H_\n#define XENOLITH_BACKEND_VK_XLVKTABLE_H_\n\n"
				"namespace STAPPLER_VERSIONIZED stappler::xenolith::vk {\n\n"
		<< "struct SP_PUBLIC LoaderTable {\n"
				"\tLoaderTable(PFN_vkGetInstanceProcAddr addr);\n\n" << loaderHeader.weak() << "};\n\n"
		<< "struct SP_PUBLIC InstanceTable {\n"
				"#if VK_HOOK_DEBUG\n\tstatic InstanceTable makeHooks();\n#endif /* VK_HOOK_DEBUG */\n\n"
				"\tInstanceTable(PFN_vkGetInstanceProcAddr addr, VkInstance instance);\n\n" << instanceHeader.weak() << "};\n\n"
		<< "struct SP_PUBLIC DeviceTable {\n"
				"#if VK_HOOK_DEBUG\n\tstatic DeviceTable makeHooks();\n#endif /* VK_HOOK_DEBUG */\n\n"
				"\tDeviceTable(PFN_vkGetDeviceProcAddr addr, VkDevice device);\n\n" << deviceHeader.weak() << "};\n"
		<< SOURCE_PREDEFINED_PROTO
		<< "\n}\n\n#endif // XENOLITH_BACKEND_VK_XLVKTABLE_H_\n";

	auto sourcePath = filesystem::currentDir<Interface>("gen/XLVkTable.cc");
	filesystem::mkdir(FileInfo(filepath::root(sourcePath)));
	filesystem::remove(FileInfo(sourcePath));

	std::ofstream sourceFile(sourcePath.data());
	sourceFile
			<< FILE_HEADER_STRING << "\n#include \"XLVkTable.h\"\n\n"
			<< "namespace STAPPLER_VERSIONIZED stappler::xenolith::vk {\n"
			<< SOURCE_PREDEFINED_FUNCTIONS << "\n\n"
			<< "LoaderTable::LoaderTable(PFN_vkGetInstanceProcAddr addr)\n"
			<< loaderConstructor.weak() << "{ }\n\n"
			<< "InstanceTable::InstanceTable(PFN_vkGetInstanceProcAddr addr, VkInstance instance)\n"
			<< instanceConstructor.weak() << "{ }\n\n"
			<< "DeviceTable::DeviceTable(PFN_vkGetDeviceProcAddr addr, VkDevice device)\n"
			<< deviceConstructor.weak() << "{ }\n\n"
			<< "#if VK_HOOK_DEBUG\n"
			<< instanceHooks.weak() << deviceHooks.weak()
			<< "\nstatic PFN_vkVoidFunction getInstanceHookAddr(VkInstance instance, const char* "
			   "pName) {\n"
			<< instanceHooksAddr.weak() << "\treturn nullptr;\n}\n\n"
			<< "\nstatic PFN_vkVoidFunction getDeviceHookAddr(VkDevice instance, const char* "
			   "pName) {\n"
			<< deviceHooksAddr.weak() << "\treturn nullptr;\n}\n\n"
			<< "InstanceTable InstanceTable::makeHooks() {\n\treturn "
			   "InstanceTable(&getInstanceHookAddr, nullptr);\n}\n\n"
			<< "DeviceTable DeviceTable::makeHooks() {\n\treturn DeviceTable(&getDeviceHookAddr, "
			   "nullptr);\n}\n\n"
			<< "#endif /* VK_HOOK_DEBUG */\n\n"
			<< "}\n";
}

