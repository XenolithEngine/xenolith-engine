struct VkRegistryReader {
	using Parser = html::Parser<VkRegistryReader, StringView, VkRegistryReaderTag>;
	using Tag = VkRegistryReaderTag;

	enum Section {
		None,
		Types,
		Tags,
		Commands,
		Feature,
		Extensions,
		Platforms,
		Enums,
	};

	inline void onBeginTag(Parser &p, Tag &tag) {
		switch (_section) {
		case Section::None:
			if (tag.name == "feature") {
				auto &v = _features.emplace_back(VkRegistryFeature());
				tag.feature = &v;
			}
			break;
		case Section::Types:
			if (tag.name == "type" && p.tagStack.back().type == nullptr) {
				auto &v = _types.emplace_back(VkRegistryType());
				tag.type = &v;
			}
			break;
		case Section::Commands:
			if (tag.name == "command") {
				auto &v = _commands.emplace_back(VkRegistryCommand());
				tag.command = &v;
			}
			break;
		case Section::Feature:
			if (tag.name == "require") {
				auto &v = p.tagStack.back().feature->_requires.emplace_back(VkRegistryRequire());
				tag.require = &v;
			} else if (tag.name == "command" && p.tagStack.back().require) {
				auto v = &p.tagStack.back().require->commands.emplace_back(StringView());
				tag.string = v;
			}
			break;
		case Section::Extensions:
			if (tag.name == "extension") {
				auto &v = _extensions.emplace_back(VkRegistryExtension());
				tag.extension = &v;
			} else if (tag.name == "require" && p.tagStack.back().extension) {
				auto &v = p.tagStack.back().extension->commands.emplace_back(VkRegistryRequire());
				tag.require = &v;
			} else if (tag.name == "command" && p.tagStack.back().require) {
				auto v = &p.tagStack.back().require->commands.emplace_back(StringView());
				tag.string = v;
			}
			break;
		case Section::Enums: break;
		case Section::Tags:
		case Section::Platforms: break;
		}
		if (tag.name == "enums") {
			auto &v = _enums.emplace_back(VkRegistryEnum());
			tag.enum_ = &v;
		}
		// log::source().debug("onBeginTag", tag.name);
	}

	inline void onEndTag(Parser &p, Tag &tag, bool isClosable) {
		// log::source().debug("onEndTag", tag.name);
	}

	inline void onTagAttribute(Parser &p, Tag &tag, StringView &name, StringView &value) {
		if (tag.name == "command" && tag.command) {
			if (name == "successcodes") {
				value.split<StringView::Chars<','>>(
						[&](StringView str) { tag.command->successcodes.emplace_back(str); });
			} else if (name == "errorcodes") {
				value.split<StringView::Chars<','>>(
						[&](StringView str) { tag.command->errorcodes.emplace_back(str); });
			} else if (name == "name") {
				tag.command->name = value;
			} else if (name == "alias") {
				tag.command->alias = value;
			} else {
				//log::source().warn("VkRegistryReader", "Unknown <command> attribute: ", name);
			}
		} else if (tag.name == "command" && tag.string && name == "name") {
			*tag.string = value;
		} else if (tag.name == "type" && tag.type) {
			if (name == "category") {
				tag.type->category = value;
			} else if (name == "parent") {
				tag.type->parent = value;
			} else if (name == "alias") {
				tag.type->alias = value;
			} else if (name == "name") {
				tag.type->name = value;
			} else if (name == "structextends" || name == "returnedonly" || name == "objtypeenum"
					|| name == "requires" || name == "allowduplicate" || name == "comment"
					|| name == "deprecated" || name == "api" || name == "bitvalues") {
				// do nothing
			} else {
				//log::source().warn("VkRegistryReader", "Unknown <type> attribute: ", name);
			}
		} else if (tag.name == "feature" && name == "name" && tag.feature) {
			tag.feature->name = value;
		} else if (tag.name == "require" && tag.require) {
			if (name == "extension") {
				tag.require->extension = value;
			} else if (name == "feature") {
				tag.require->feature = value;
			} else if (name == "depends") {
				tag.require->depends = value;
			} else {
				//log::source().warn("VkRegistryReader", "Unknown <require> attribute: ", name);
			}
		} else if (tag.name == "extension" && tag.extension) {
			if (name == "name") {
				tag.extension->name = value;
			} else if (name == "supported") {
				tag.extension->supported = value;
			} else if (name == "type") {
				tag.extension->type = value;
			} else if (name == "requires") {
				value.split<StringView::Chars<','>>(
						[&](StringView v) { tag.extension->_requires.emplace_back(v); });
			} else {
				//log::source().warn("VkRegistryReader", "Unknown <extension> attribute: ", name);
			}
		} else if (tag.name == "enum") {
			// do nothing
		} else if (tag.name == "enums" && tag.enum_) {
			if (name == "name") {
				tag.enum_->name = value;
			} else if (name == "type") {
				tag.enum_->type = value;
			}
		} else if (tag.name == "platforms" || tag.name == "platform" || tag.name == "tags"
				|| tag.name == "tag" || tag.name == "types" || tag.name == "member"
				|| tag.name == "enums" || tag.name == "enum" || tag.name == "unused"
				|| tag.name == "commands" || tag.name == "param" || tag.name == "feature"
				|| tag.name == "type" || tag.name == "component" || tag.name == "format"
				|| tag.name == "spirvimageformat" || tag.name == "plane"
				|| tag.name == "spirvextensions" || tag.name == "enable"
				|| tag.name == "spirvextension" || tag.name == "spirvcapabilities"
				|| tag.name == "spirvcapability" || tag.name == "syncsupport"
				|| tag.name == "syncstage" || tag.name == "syncpipelinestage"
				|| tag.name == "syncpipeline" || tag.name == "syncaccess"
				|| tag.name == "syncequivalent" || tag.name == "sync" || tag.name == "extensions"
				|| tag.name == "remove" || tag.name == "syncequivalent") {
		} else {
			log::source().debug("onTagAttribute", tag.name, ": ", name, " = ", value);
		}
	}

	inline void onPushTag(Parser &p, Tag &tag) {
		if (_section == None) {
			if (tag.name == "commands" && _section == None) {
				_section = Commands;
			} else if (tag.name == "types" && _section == None) {
				_section = Types;
			} else if (tag.name == "feature" && _section == None) {
				_section = Feature;
			} else if (tag.name == "extensions" && _section == None) {
				_section = Extensions;
			} else if (tag.name == "platforms" && _section == None) {
				_section = Platforms;
			} else if (tag.name == "enums" && _section == None) {
				_section = Enums;
			} else if (tag.name == "tags" && _section == None) {
				_section = Tags;
			}
		} else if (tag.name == "proto") {
			tag.proto = &p.tagStack.back().command->proto;
		} else if (tag.name == "param" && p.tagStack.back().command) {
			tag.proto = &p.tagStack.back().command->params.emplace_back(VkRegistryCommandProto());
		} else if (tag.name == "type" && p.tagStack.back().proto) {
			auto str = &p.tagStack.back().proto->strings.emplace_back(StringView());
			tag.string = str;
		} else if (tag.name == "name" && p.tagStack.back().proto) {
			auto str = &p.tagStack.back().proto->strings.emplace_back(StringView());
			tag.string = str;
		} else if (tag.name == "name" && p.tagStack.back().type) {
			tag.string = &p.tagStack.back().type->name;
		}
	}

	inline void onPopTag(Parser &p, Tag &tag) {
		switch (_section) {
		case None: break;
		case Types:
			if (tag.name == "types") {
				_section = None;
			}
			break;
		case Tags:
			if (tag.name == "tags") {
				_section = None;
			}
			break;
		case Commands:
			if (tag.name == "commands") {
				_section = None;
			}
			break;
		case Feature:
			if (tag.name == "feature") {
				_section = None;
			}
			break;
		case Extensions:
			if (tag.name == "extensions") {
				_section = None;
			}
			break;
		case Platforms:
			if (tag.name == "platforms") {
				_section = None;
			}
			break;
		case Enums:
			if (tag.name == "enums") {
				_section = None;
			}
			break;
		}
		if (tag.name == "command" && tag.command) {
			tag.command->name = tag.command->proto.name;
		} else if (tag.string && tag.name == "name" && p.tagStack.at(p.tagStack.size() - 2).proto) {
			p.tagStack.at(p.tagStack.size() - 2).proto->name = *tag.string;
		} else if (tag.string && tag.name == "type" && p.tagStack.at(p.tagStack.size() - 2).proto) {
			p.tagStack.at(p.tagStack.size() - 2).proto->type = *tag.string;
		}
		// log::source().debug("onPopTag", tag.name);
	}

	inline void onInlineTag(Parser &p, Tag &tag) {
		// log::source().debug("onInlineTag", tag.name);
	}

	inline void onTagContent(Parser &p, Tag &tag, StringView &s) {
		if ((tag.name == "proto" || tag.name == "param") && tag.proto) {
			tag.proto->strings.emplace_back(normalizeString(s));
		} else if (tag.string) {
			*tag.string = normalizeString(s);
		}
		// log::source().debug("onTagContent", tag.name, ": ", s);
	}

	StringView normalizeString(StringView s) {
		auto tmp = s;
		tmp.trimChars<StringView::WhiteSpace>();
		if (tmp.empty()) {
			return StringView(" ");
		} else if (tmp == "*") {
			return StringView("* ");
		} else {
			return s;
		}
	}

	Section _section = None;
	Vector<VkRegistryCommand> _commands;
	Vector<VkRegistryType> _types;
	Vector<VkRegistryFeature> _features;
	Vector<VkRegistryExtension> _extensions;
	Vector<VkRegistryEnum> _enums;
};

bool RegistryData::load() {
	NetworkHandle h;
	h.init(network::Method::Get,
			"https://raw.githubusercontent.com/KhronosGroup/Vulkan-Docs/main/xml/vk.xml");

	h.setReceiveCallback([&](char *d, size_t len) {
		data << StringView(d, len);
		return len;
	});

	if (h.perform()) {
		parse();
		return true;
	}
	return false;
}

StringView RegistryData::getRootType(VkRegistryCommand &cmd) {
	if (cmd.name == "vkGetInstanceProcAddr") {
		return StringView();
	} else if (cmd.name == "vkGetDeviceProcAddr") {
		return StringView("VkInstance");
	}

	if (!cmd.params.empty()) {
		auto type = cmd.params.at(0).type;
		auto it = types.find(type);
		if (it != types.end()) {
			auto ret = &it->second;
			while (ret->canonical) { ret = ret->canonical; }

			while (ret->name != "VkInstance" && ret->name != "VkDevice" && ret->parentType) {
				ret = ret->parentType;
			}

			return ret->name;
		}
	}
	return StringView();
}

VkRegistryCommand *RegistryData::getCommand(StringView cmd) {
	VkRegistryCommand *ptr = nullptr;
	auto it = commands.find(cmd);
	if (it != commands.end()) {
		ptr = &it->second;
	}
	return ptr;
}

void RegistryData::parse() {
	VkRegistryReader reader;
	auto str = StringView(data.data(), data.size());
	html::parse<VkRegistryReader, StringView, VkRegistryReaderTag>(reader, str,
			html::ParserFlags::Relaxed);

	for (auto &it : reader._types) {
		if (it.category == "handle" || it.category == "struct" || it.category == "bitmask") {
			types.emplace(it.name, it);
		}
	}

	for (auto &it : types) {
		if (!it.second.parent.empty()) {
			auto v = types.find(it.second.parent);
			if (v != types.end()) {
				it.second.parentType = &v->second;
			}
		}
		if (!it.second.alias.empty()) {
			auto v = types.find(it.second.alias);
			if (v != types.end()) {
				it.second.canonical = &v->second;
				while (it.second.canonical->canonical) {
					it.second.canonical = it.second.canonical->canonical;
				}
				it.second.canonical->aliases.emplace_back(it.second.name);
			}
		}
	}

	for (auto &it : reader._commands) { commands.emplace(it.name, it); }

	for (auto &it : commands) {
		if (!it.second.alias.empty()) {
			auto v = commands.find(it.second.alias);
			if (v != commands.end()) {
				it.second.canonical = &v->second;
				while (it.second.canonical->canonical) {
					it.second.canonical = it.second.canonical->canonical;
				}
				it.second.canonical->aliases.emplace_back(it.second.name);
				it.second.rootType = getRootType(*it.second.canonical);
			}
		} else {
			it.second.rootType = getRootType(it.second);
		}
	}

	features = std::move(reader._features);
	extensions = std::move(reader._extensions);
	enums = std::move(reader._enums);

	for (auto &ext : extensions) {
		if (ext.supported == "disabled") {
			continue;
		}
		for (auto &req : ext.commands) {
			for (auto &c : req.commands) {
				auto it = commands.find(c);
				if (it != commands.end()) {
					if (!req.feature.empty()) {
						it->second._requires.emplace_back(ext.name, req.feature);
					}
					if (!req.extension.empty()) {
						it->second._requires.emplace_back(ext.name, req.extension);
					}
					if (!req.depends.empty()) {
						req.depends.split<StringView::Chars<','>>([&](StringView str) {
							it->second._requires.emplace_back(ext.name, str);
						});
					}
				}
			}
		}
	}
}

String RegistryData::makeGuard(StringView name, SpanView<Pair<StringView, StringView>> reqs) {
	StringStream out;
	if (reqs.empty()) {
		out << "defined(" << name << ")";
	} else if (reqs.size() == 1) {
		auto &tmp = reqs.front();
		out << "defined(" << tmp.first << ") && defined(" << tmp.second << ")";
	} else {
		bool first = true;
		for (auto &req : reqs) {
			if (first) {
				first = false;
			} else {
				out << " || ";
			}
			out << "(defined(" << req.first << ") && defined(" << req.second << "))";
		}
	}
	return out.str();
}

